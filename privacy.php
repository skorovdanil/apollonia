            положениями законодательства Российской Федерации о персональных данных, в том числе требованиями к
            защите персональных данных, документами, определяющими политику оператора в отношении обработки
            персональных данных, локальными актами по вопросам обработки персональных данных, и (или) обучение
            указанных сотрудников;</li>
        <li>Проведение вводного и текущего инструктажей для работников, допущенных к обработке персональных
