    <div class="privacy__title_text">4. Термины и определения</div>

    <ul type="square">
        <li>Персональные данные (далее ПДн) — любая информация, относящаяся к прямо или косвенно определенному
            или определяемому физическому лицу (субъекту персональных данных);</li>
        <li>Оператор персональных данных (оператор) — юридическое лицо, самостоятельно организующее и (или)
            осуществляющее обработку персональных данных, а также определяющее цели обработки персональных
            данных, состав персональных данных, подлежащих обработке, действия (операции), совершаемые с
            персональными данными;</li>
        <li>Обработка персональных данных — любое действие (операция) или совокупность действий (операций) с
            персональными данными, совершаемых с использованием средств автоматизации или без их использования,
            включая сбор; запись; систематизацию; накопление; хранение; уточнение (обновление, изменение);
            извлечение; использование; передачу (распространение, предоставление, доступ); обезличивание;
            блокирование; удаление; уничтожение;</li>
        <li>Автоматизированная обработка персональных данных — обработка персональных данных с помощью средств
            вычислительной техники;</li>
        <li>Распространение персональных данных — действия, направленные на раскрытие персональных данных
            неопределенному кругу лиц;</li>
        <li>Предоставление персональных данных — действия, направленные на раскрытие персональных данных
            определенному лицу или определенному кругу лиц;</li>
        <li>Блокирование персональных данных — временное прекращение обработки персональных данных (за
            исключением случаев, если обработка необходима для уточнения персональных данных);</li>
        <li>Уничтожение персональных данных — действия, в результате которых становится невозможным восстановить
            содержание персональных данных в информационной системе персональных данных и (или) в результате
            которых уничтожаются материальные носители персональных данных;</li>
        <li>Обезличивание персональных данных — действия, в результате которых становится невозможным без
            использования дополнительной информации определить принадлежность персональных данных конкретному
            субъекту персональных данных;</li>
        <li>Информационная система персональных данных — совокупность содержащихся в базах данных персональных
            данных и обеспечивающих их обработку информационных технологий и технических средств;</li>
        <li>Трансграничная передача персональных данных — передача персональных данных на территорию
            иностранного государства органу власти иностранного государства, иностранному физическому лицу или
            иностранному юридическому лицу.</li>
    </ul>

